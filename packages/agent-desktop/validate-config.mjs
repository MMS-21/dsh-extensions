import {dshProfilePath} from '../../scripts/local-paths.mjs';
import {dshRuntimeRoot} from '../../scripts/local-paths.mjs';
import {createRequire} from 'node:module';
import {readFileSync,writeFileSync} from 'node:fs';
import {pathToFileURL} from 'node:url';
import assert from 'node:assert/strict';
const runtime=dshRuntimeRoot();
const require=createRequire(runtime+'package.json');
const YAML=require('yaml');
const {Config}=await import(pathToFileURL(runtime+'node_modules/@deepseek-ai/dsh-mcp-client/lib/index.js').href);
const customTags=[{tag:'tag:yaml.org,2002:js',resolve:value=>value}];
const profile=dshProfilePath('cordis.patch.yml');
const original=readFileSync(profile,'utf8');
const entry=readFileSync(new URL('./dsh-entry.yml',import.meta.url),'utf8');
const snippet=YAML.parseDocument(entry,{customTags});assert.equal(snippet.errors.length,0);
const config=snippet.toJS()[0].insert[0].config;
const resolved=Config(config);assert.equal(resolved.transport,'stdio');assert.equal(resolved.args[0],'mcp');
assert.equal(resolved.command.includes('win32-x64.exe'),true);
const installed=process.argv.includes('--installed');
const candidate=installed?original:original.trimEnd()+'\n\n# agent-desktop native MCP integration\n'+entry;
const parsed=YAML.parseDocument(candidate,{customTags});assert.equal(parsed.errors.length,0,parsed.errors.map(error=>error.message).join('; '));
assert.ok(Array.isArray(parsed.toJS()));
assert.equal(parsed.toJS().at(-1).insert[0].id,'mcp-agent-desktop');
assert.equal(parsed.toJS().flatMap(patch=>patch.insert||[]).filter(plugin=>plugin.id==='mcp-agent-desktop').length,1,'exactly one server entry');
writeFileSync(new URL('./config-validation.json',import.meta.url),JSON.stringify({validYaml:true,actualDshSchema:true,serverName:resolved.serverName,transport:resolved.transport,headed:false,trace:false},null,2));
console.log(`PASS: ${installed?'installed profile':'proposed profile'} is valid YAML with exactly one server entry; actual DSH rc.3 MCP Config accepts its settings.`);
