import fs from 'node:fs';
import path from 'node:path';
import {createRequire} from 'node:module';
import {fileURLToPath} from 'node:url';
const here=path.dirname(fileURLToPath(import.meta.url));
const local=createRequire(import.meta.url);
let toolchain=local;
try{local.resolve('esbuild');local.resolve('motion/react');}catch{
 if(!process.env.DSH_UI_TOOLCHAIN)throw Error('Install devDependencies or set DSH_UI_TOOLCHAIN to an existing package.json with esbuild and motion.');
 toolchain=createRequire(path.resolve(process.env.DSH_UI_TOOLCHAIN));
}
const {build}=toolchain('esbuild');
const result=await build({entryPoints:[path.join(here,'src/animated-icons.tsx')],bundle:true,write:false,metafile:true,format:'cjs',platform:'browser',target:'chrome120',jsx:'automatic',external:['react','react/*','react-dom','react-dom/*'],alias:{'motion/react':toolchain.resolve('motion/react')},define:{'process.env.NODE_ENV':'"production"'},minify:true,legalComments:'inline'});
const source=fs.readFileSync(path.join(here,'src/theme-client.js'),'utf8');
if(!source.includes('/*__ANIMATED_ICONS__*/'))throw Error('Missing generated-icons marker');
const code='const animatedIcons=(()=>{const module={exports:{}};const exports=module.exports;'+result.outputFiles[0].text+';return module.exports;})();';
fs.writeFileSync(path.join(here,'client.js'),'// Generated by build-client.mjs; edit src/theme-client.js and src/animated-icons.tsx.\n'+source.replace('/*__ANIMATED_ICONS__*/',()=>code));
const licenses=new Map();
for(const input of Object.keys(result.metafile.inputs)){
 let dir=path.dirname(path.resolve(input));
 while(path.dirname(dir)!==dir){
  const manifest=path.join(dir,'package.json');
  if(fs.existsSync(manifest)){
   const pkg=JSON.parse(fs.readFileSync(manifest,'utf8'));
   if(pkg.name&&['motion','framer-motion','motion-dom','motion-utils','@animateicons/react'].includes(pkg.name)){
    const license=['LICENSE','LICENSE.md'].map(name=>path.join(dir,name)).find(fs.existsSync);
    if(license)licenses.set(pkg.name,pkg.name+' '+pkg.version+'\n'+fs.readFileSync(license,'utf8'));
    break;
   }
  }
  dir=path.dirname(dir);
 }
}
fs.writeFileSync(path.join(here,'MOTION-LICENSES.txt'),[...licenses.values()].join('\n\n'));
console.log('Built complete Motion icon components into shell client: '+result.outputFiles[0].text.length+' icon-runtime bytes');
